package net.fathom.optimizations.fabric.gfx;

import java.awt.AlphaComposite;
import java.awt.BasicStroke;
import java.awt.Color;
import java.awt.Graphics2D;
import java.awt.LinearGradientPaint;
import java.awt.MultipleGradientPaint;
import java.awt.RadialGradientPaint;
import java.awt.RenderingHints;
import java.awt.geom.AffineTransform;
import java.awt.geom.Ellipse2D;
import java.awt.geom.Path2D;
import java.awt.geom.Point2D;
import java.awt.image.BufferedImage;
import java.awt.image.ConvolveOp;
import java.awt.image.Kernel;
import java.util.HashMap;
import java.util.Map;

import net.fathom.optimizations.generated.FathomTheme;
import net.fathom.optimizations.generated.GraphiteTokens;
import net.fathom.optimizations.generated.Mark;
import net.fathom.optimizations.generated.Wordmark;

/**
 * The wordmark and the mark, rasterised at the size they are drawn at.
 *
 * <h2>The geometry is not here</h2>
 *
 * <p>The letter outlines are {@link Wordmark}, generated by
 * {@code tools/generate-wordmark.py} from the launcher's own Geist, and the
 * mark's are {@link Mark}, generated by {@code assets/brand/build-brand.mjs}:
 * the same paths the launcher draws as SVG. What this class does is the part that
 * depends on the pixel size, the way the launcher's {@code wordmarkLayout}
 * does: the optical tier is chosen by the ascender in device pixels (SemiBold
 * and a little looser up to {@code WORDMARK_SMALL_MAX}, Medium above), and up
 * to {@code WORDMARK_TEXT_MAX} the x-height is rounded to whole pixels and the
 * baseline placed on a pixel row.
 *
 * <h2>Once per size</h2>
 *
 * <p>Java2D fills the outlines anti-aliased into a sheet of its own, the first
 * time a size is asked for, and the result is kept. Drawing the wordmark after
 * that is one textured quad: no path work, no allocation, one texture bind. The
 * menu and the hub each ask for one size of each, so the sheet holds a
 * handful of entries for the life of the window. It is its own sheet, not the icon sheet,
 * because a large wordmark on a high-density display is wider than the icons'
 * 512 pixels.
 *
 * <h2>Their own inks</h2>
 *
 * <p>Both are rasterised in the brand's inks: the wordmark ivory, taking the
 * arc's blue over its last letters, and the mark in its gradients, glow and
 * halo, as on the app icon. They are drawn under a white tint, so a screen's
 * colour only fades them.
 */
final class BrandArt {

    private static final int SHEET = 1024;
    private static final int MAX_CAP = 256;

    /** Where one raster lives on the sheet, and its size in device pixels. */
    static final class Entry {
        final float u0;
        final float v0;
        final float u1;
        final float v1;
        final int width;
        final int height;
        /** Pixels of room left of the ink and above the ascender. */
        final int pad;

        Entry(float u0, float v0, float u1, float v1, int width, int height, int pad) {
            this.u0 = u0;
            this.v0 = v0;
            this.u1 = u1;
            this.v1 = v1;
            this.width = width;
            this.height = height;
            this.pad = pad;
        }
    }

    /** One optical tier at one size: the path, its scale and its whole-pixel box. */
    static final class Layout {
        final String path;
        final float scale;
        /** Ink width in wordmark units, for the ink's gradient. */
        final float units;
        /** Ink width, rounded up. */
        final int width;
        /** Ascender to baseline, rounded up; the baseline sits at the bottom. */
        final int ascender;
        /** The x-height drawn, in device pixels: whole up to the text tier. */
        final float xHeight;

        Layout(String path, float scale, float units, int width, int ascender, float xHeight) {
            this.path = path;
            this.scale = scale;
            this.units = units;
            this.width = width;
            this.ascender = ascender;
            this.xHeight = xHeight;
        }
    }

    private static final Entry EMPTY = new Entry(0f, 0f, 0f, 0f, 0, 0, 0);

    private final Atlas atlas;
    private final Map<Integer, Entry> wordmarks = new HashMap<Integer, Entry>();
    private final Map<Integer, Entry> marks = new HashMap<Integer, Entry>();
    /** The last lookup, which is nearly every lookup: a screen draws one size. */
    private int lastCap = -1;
    private Entry lastEntry;
    private int lastMark = -1;
    private Entry lastMarkEntry;

    BrandArt(Atlas.BeforeUpload beforeUpload) {
        this.atlas = new Atlas(SHEET, beforeUpload);
    }

    Atlas atlas() {
        return atlas;
    }

    void create() {
        atlas.create();
    }

    void reset() {
        forget();
        atlas.delete();
        atlas.create();
    }

    void delete() {
        forget();
        atlas.delete();
    }

    private void forget() {
        wordmarks.clear();
        marks.clear();
        lastCap = -1;
        lastEntry = null;
        lastMark = -1;
        lastMarkEntry = null;
    }

    // -----------------------------------------------------------------------
    // The wordmark
    // -----------------------------------------------------------------------

    /** An ascender height in device pixels, held to the wordmark's minimum. */
    static int clampCap(int capPixels) {
        return Math.max(Math.round(GraphiteTokens.WORDMARK_CAP_MIN_PX), Math.min(MAX_CAP, capPixels));
    }

    /** The tier, scale and box for an ascender height in device pixels. */
    static Layout layout(int cap) {
        String path;
        float width;
        float xHeight;
        if (cap <= GraphiteTokens.WORDMARK_SMALL_MAX) {
            path = Wordmark.SMALL_PATH;
            width = Wordmark.SMALL_WIDTH;
            xHeight = Wordmark.SMALL_X_HEIGHT;
        } else if (cap <= GraphiteTokens.WORDMARK_TEXT_MAX) {
            path = Wordmark.TEXT_PATH;
            width = Wordmark.TEXT_WIDTH;
            xHeight = Wordmark.TEXT_X_HEIGHT;
        } else {
            path = Wordmark.DISPLAY_PATH;
            width = Wordmark.DISPLAY_WIDTH;
            xHeight = Wordmark.DISPLAY_X_HEIGHT;
        }
        float exact = cap * xHeight / Wordmark.CAP;
        float drawn = cap <= GraphiteTokens.WORDMARK_TEXT_MAX ? Math.max(1, Math.round(exact)) : exact;
        float scale = drawn / xHeight;
        return new Layout(path, scale, width, (int) Math.ceil(width * scale),
                (int) Math.ceil(Wordmark.CAP * scale), drawn);
    }

    /**
     * The ascender, near {@code near}, whose drawn x-height is exactly
     * {@code xHeight} device pixels -- for the lockup, where the word's
     * x-height is the top of the mark's plane. {@code near} if none is.
     */
    static int capForXHeight(int xHeight, int near) {
        int best = clampCap(near);
        int bestDistance = Integer.MAX_VALUE;
        for (int cap = clampCap(near - 12); cap <= clampCap(near + 12); cap++) {
            if (Math.round(layout(cap).xHeight) != xHeight) {
                continue;
            }
            int distance = Math.abs(cap - near);
            if (distance < bestDistance) {
                best = cap;
                bestDistance = distance;
            }
        }
        return best;
    }

    /** Room around the ink for the round letters' overshoot, in device pixels. */
    static int pad(int cap) {
        return 1 + (int) Math.ceil(cap * Wordmark.DISPLAY_DESCENT / Wordmark.CAP);
    }

    /** The wordmark at an ascender height in device pixels, rasterising if needed. */
    Entry wordmark(int capPixels) {
        int cap = clampCap(capPixels);
        if (cap == lastCap && lastEntry != null) {
            return lastEntry;
        }
        Entry found = wordmarks.get(Integer.valueOf(cap));
        if (found == null) {
            found = rasterise(cap);
            wordmarks.put(Integer.valueOf(cap), found);
        }
        lastCap = cap;
        lastEntry = found;
        return found;
    }

    /** The ink width in device pixels at an ascender height, without rasterising. */
    static int wordmarkWidth(int capPixels) {
        return layout(clampCap(capPixels)).width;
    }

    private Entry rasterise(int cap) {
        Layout layout = layout(cap);
        int pad = pad(cap);
        int width = layout.width + pad * 2;
        int height = layout.ascender + pad * 2;
        int[] at = atlas.allocate(width, height);
        if (at == null) {
            return EMPTY;
        }
        BufferedImage image = new BufferedImage(width, height, BufferedImage.TYPE_INT_ARGB);
        Graphics2D graphics = quality(image.createGraphics());
        // The baseline on a pixel row: the box's rounding goes above the ascender.
        graphics.translate(pad, pad + (layout.ascender - Wordmark.CAP * layout.scale));
        graphics.scale(layout.scale, layout.scale);
        // Ivory, holding to word-tint-from of the way along, then warming to
        // the arc's light by the last letter.
        Color ink = colour(FathomTheme.Tokens.BRAND_WORD_INK, 1f);
        graphics.setPaint(new LinearGradientPaint(0f, 0f, layout.units, 0f,
                new float[] {0f, FathomTheme.Tokens.BRAND_WORD_TINT_FROM, 1f},
                new Color[] {ink, ink, colour(FathomTheme.Tokens.BRAND_WORD_TINT, 1f)}));
        graphics.fill(path(layout.path));
        graphics.dispose();
        atlas.upload(image, at[0], at[1]);
        return new Entry(atlas.u(at[0]), atlas.v(at[1]),
                atlas.u(at[0] + width), atlas.v(at[1] + height), width, height, pad);
    }

    // -----------------------------------------------------------------------
    // The mark
    // -----------------------------------------------------------------------

    private static final int MAX_MARK = 512;

    /** A mark height in device pixels, held to something drawable. */
    static int clampMark(int heightPixels) {
        return Math.max(8, Math.min(MAX_MARK, heightPixels));
    }

    /** The mark's width in device pixels at a height in device pixels. */
    static int markWidth(int heightPixels) {
        return Math.round(clampMark(heightPixels) * Mark.BOX_WIDTH / Mark.BOX_HEIGHT);
    }

    /**
     * Room round the mark's box for the halo and the star's glow, which spill
     * past it: the halo reaches 21 grid px below the arc.
     */
    static int markPad(int heightPixels) {
        return 2 + (int) Math.ceil(24f * clampMark(heightPixels) / Mark.BOX_HEIGHT);
    }

    /** The mark at a height in device pixels, with its halo, rasterising if needed. */
    Entry mark(int heightPixels) {
        int height = clampMark(heightPixels);
        if (height == lastMark && lastMarkEntry != null) {
            return lastMarkEntry;
        }
        Entry found = marks.get(Integer.valueOf(height));
        if (found == null) {
            found = rasteriseMark(height);
            marks.put(Integer.valueOf(height), found);
        }
        lastMark = height;
        lastMarkEntry = found;
        return found;
    }

    private Entry rasteriseMark(int height) {
        int pad = markPad(height);
        int width = markWidth(height) + pad * 2;
        int tall = height + pad * 2;
        int[] at = atlas.allocate(width, tall);
        if (at == null) {
            return EMPTY;
        }
        float k = height / Mark.BOX_HEIGHT;
        AffineTransform grid = new AffineTransform();
        grid.translate(pad - Mark.BOX_X * k, pad - Mark.BOX_Y * k);
        grid.scale(k, k);

        BufferedImage image = new BufferedImage(width, tall, BufferedImage.TYPE_INT_ARGB);
        Graphics2D graphics = quality(image.createGraphics());
        graphics.transform(grid);

        // The halo: an ellipse lit from its centre, the icon's radial gradient.
        AffineTransform ellipse = new AffineTransform();
        ellipse.translate(Mark.HALO_CX, Mark.HALO_CY);
        ellipse.scale(Mark.HALO_RX, Mark.HALO_RY);
        graphics.setPaint(new RadialGradientPaint(new Point2D.Float(0f, 0f), 1f, new Point2D.Float(0f, 0f),
                new float[] {0f, 1f},
                new Color[] {colour(FathomTheme.Tokens.BRAND_HALO, FathomTheme.Tokens.BRAND_HALO_ALPHA),
                        colour(FathomTheme.Tokens.BRAND_HALO, 0f)},
                MultipleGradientPaint.CycleMethod.NO_CYCLE, MultipleGradientPaint.ColorSpaceType.SRGB, ellipse));
        graphics.fill(new Ellipse2D.Float(Mark.HALO_CX - Mark.HALO_RX, Mark.HALO_CY - Mark.HALO_RY,
                Mark.HALO_RX * 2f, Mark.HALO_RY * 2f));

        // The arc, its gradient laid along its own box as SVG's
        // objectBoundingBox lays it.
        AffineTransform box = new AffineTransform();
        box.translate(Mark.ARC_X, Mark.ARC_Y);
        box.scale(Mark.ARC_WIDTH, Mark.ARC_HEIGHT);
        graphics.setPaint(new LinearGradientPaint(new Point2D.Float(Mark.ORBIT_X1, Mark.ORBIT_Y1),
                new Point2D.Float(Mark.ORBIT_X2, Mark.ORBIT_Y2), Mark.ORBIT_STOPS,
                new Color[] {colour(FathomTheme.Tokens.BRAND_ORBIT_START, 1f),
                        colour(FathomTheme.Tokens.BRAND_ORBIT_LIGHT, 1f),
                        colour(FathomTheme.Tokens.BRAND_ORBIT_MID, 1f),
                        colour(FathomTheme.Tokens.BRAND_ORBIT_TIP, 1f)},
                MultipleGradientPaint.CycleMethod.NO_CYCLE, MultipleGradientPaint.ColorSpaceType.SRGB, box));
        graphics.fill(path(Mark.ARC));
        graphics.setPaint(colour(FathomTheme.Tokens.BRAND_TAPER, FathomTheme.Tokens.BRAND_TAPER_ALPHA));
        graphics.fill(path(Mark.TAPER));

        // The star's glow: filled on its own premultiplied layer, blurred, and
        // laid under the star.
        BufferedImage glow = new BufferedImage(width, tall, BufferedImage.TYPE_INT_ARGB_PRE);
        Graphics2D glowGraphics = quality(glow.createGraphics());
        glowGraphics.transform(grid);
        glowGraphics.setPaint(colour(FathomTheme.Tokens.BRAND_STAR_GLOW, 1f));
        glowGraphics.fill(path(Mark.STAR_GLOW));
        glowGraphics.dispose();
        Graphics2D layer = image.createGraphics();
        layer.setComposite(AlphaComposite.getInstance(AlphaComposite.SRC_OVER,
                FathomTheme.Tokens.BRAND_STAR_GLOW_ALPHA));
        layer.drawImage(blur(glow, FathomTheme.Tokens.BRAND_STAR_GLOW_BLUR * k), 0, 0, null);
        layer.dispose();

        graphics.setPaint(colour(FathomTheme.Tokens.BRAND_STAR, 1f));
        graphics.fill(path(Mark.STAR));
        graphics.setPaint(colour(FathomTheme.Tokens.BRAND_STAR_CORE, FathomTheme.Tokens.BRAND_STAR_CORE_ALPHA));
        graphics.setStroke(new BasicStroke(Mark.STAR_CORE_WIDTH, BasicStroke.CAP_BUTT, BasicStroke.JOIN_MITER));
        graphics.draw(path(Mark.STAR_CORE));
        graphics.dispose();

        atlas.upload(image, at[0], at[1]);
        return new Entry(atlas.u(at[0]), atlas.v(at[1]),
                atlas.u(at[0] + width), atlas.v(at[1] + tall), width, tall, pad);
    }

    private static Path2D.Float path(String d) {
        Path2D.Float path = new Path2D.Float(Path2D.WIND_NON_ZERO);
        SvgPath.append(d, path);
        return path;
    }

    private static Graphics2D quality(Graphics2D graphics) {
        graphics.setRenderingHint(RenderingHints.KEY_ANTIALIASING, RenderingHints.VALUE_ANTIALIAS_ON);
        graphics.setRenderingHint(RenderingHints.KEY_STROKE_CONTROL, RenderingHints.VALUE_STROKE_PURE);
        graphics.setRenderingHint(RenderingHints.KEY_RENDERING, RenderingHints.VALUE_RENDER_QUALITY);
        graphics.setRenderingHint(RenderingHints.KEY_COLOR_RENDERING, RenderingHints.VALUE_COLOR_RENDER_QUALITY);
        return graphics;
    }

    /** A separable Gaussian blur, on premultiplied pixels so its edges do not darken. */
    private static BufferedImage blur(BufferedImage source, float sigma) {
        if (sigma < 0.25f) {
            return source;
        }
        int radius = (int) Math.ceil(sigma * 3f);
        float[] weights = new float[radius * 2 + 1];
        float sum = 0f;
        for (int i = -radius; i <= radius; i++) {
            weights[i + radius] = (float) Math.exp(-(i * i) / (2f * sigma * sigma));
            sum += weights[i + radius];
        }
        for (int i = 0; i < weights.length; i++) {
            weights[i] /= sum;
        }
        ConvolveOp across = new ConvolveOp(new Kernel(weights.length, 1, weights), ConvolveOp.EDGE_ZERO_FILL, null);
        ConvolveOp down = new ConvolveOp(new Kernel(1, weights.length, weights), ConvolveOp.EDGE_ZERO_FILL, null);
        return down.filter(across.filter(source, null), null);
    }

    /** An ARGB token as a Java2D colour, at an alpha of 0-1. */
    private static Color colour(int argb, float alpha) {
        return new Color((argb >> 16) & 0xFF, (argb >> 8) & 0xFF, argb & 0xFF,
                Math.round(Math.max(0f, Math.min(1f, alpha)) * 255f));
    }
}
